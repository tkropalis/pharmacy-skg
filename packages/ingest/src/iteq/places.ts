/** The lookup key: capitals without accents, single spaces. */
function keyOf(text: string): string {
  return text.normalize('NFD').replace(/\p{M}/gu, '').toUpperCase().replace(/\s+/g, ' ').trim();
}

const BY_KEY = new Map(Object.entries(PLACES).map(([printed, name]) => [keyOf(printed), name]));

/**
 * The place as people write it, or as printed when it is not listed. A town and its
 * neighbourhood ("ΠΕΙΡΑΙΑΣ-ΚΑΣΤΕΛΛΑ") are named part by part: "Πειραιάς, Καστέλλα".
 */
export function placeName(printed: string): string {
  const key = keyOf(printed);
  const whole = BY_KEY.get(key);
  if (whole !== undefined) return whole;
  const parts = key.split(/\s*-\s*/);
  const named = parts.map((part) => BY_KEY.get(part));
  if (parts.length > 1 && named.every((name) => name !== undefined)) return named.join(', ');
  return printed.trim();
}
